-- Initial local database schema for Campaign Clippers.
-- API handlers use the service role and enforce identity/ownership checks.
-- Direct client table access stays disabled by RLS and explicit grants.

create table if not exists public.profiles (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete cascade,
  email text not null unique,
  name text not null,
  handle text not null default '',
  role text not null check (role in ('clipper', 'owner')),
  avatar_url text not null default '',
  bio text not null default '',
  verified boolean not null default false,
  rating numeric(3,1) not null default 0 check (rating between 0 and 5),
  rating_count integer not null default 0 check (rating_count >= 0),
  total_earnings numeric(14,2) not null default 0,
  balance numeric(14,2) not null default 0,
  total_views bigint not null default 0,
  socials jsonb not null default '{}'::jsonb,
  portfolio jsonb not null default '[]'::jsonb,
  plan text,
  created_at timestamptz not null default now()
);

create table if not exists public.campaigns (
  id bigint generated by default as identity primary key,
  owner_id bigint not null references public.profiles(id) on delete restrict,
  owner_name text not null default '',
  title text not null,
  brand_name text not null default '',
  description text not null default '',
  category text not null default 'General',
  budget numeric(14,2) not null default 0 check (budget >= 0),
  spent numeric(14,2) not null default 0 check (spent >= 0),
  reward_model text not null default 'cpm' check (reward_model in ('cpm', 'fixed', 'hybrid')),
  cpm_rate numeric(12,4) not null default 0,
  fixed_rate numeric(12,2) not null default 0,
  platforms text[] not null default '{}',
  keywords text[] not null default '{}',
  rules text not null default '',
  status text not null default 'active' check (status in ('draft', 'active', 'paused', 'completed')),
  deadline text not null default '',
  max_clippers integer not null default 10 check (max_clippers >= 0),
  thumbnail_url text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.campaign_requirements (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null unique references public.campaigns(id) on delete cascade,
  min_followers bigint not null default 0 check (min_followers >= 0),
  min_tier text not null default 'any' check (min_tier in ('any', 'bronze', 'silver', 'gold', 'elite')),
  verified_only boolean not null default false
);

create table if not exists public.applications (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.campaigns(id) on delete cascade,
  campaign_title text not null default '',
  owner_id bigint not null references public.profiles(id) on delete restrict,
  clipper_id bigint not null references public.profiles(id) on delete restrict,
  clipper_name text not null default '',
  clipper_avatar text not null default '',
  pitch text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  unique (campaign_id, clipper_id)
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  campaign_id bigint not null references public.campaigns(id) on delete cascade,
  campaign_title text not null default '',
  owner_id bigint not null references public.profiles(id) on delete restrict,
  clipper_id bigint not null references public.profiles(id) on delete restrict,
  clipper_name text not null default '',
  title text not null default '',
  video_url text not null,
  platform text not null default 'tiktok',
  views bigint not null default 0,
  likes bigint not null default 0,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  ai_quality integer,
  ai_viral integer,
  ai_caption text not null default '',
  earnings numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.connected_accounts (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  platform text not null,
  label text not null default '',
  handle text not null,
  url text not null default '',
  followers bigint not null default 0 check (followers >= 0),
  engagement numeric(7,3) not null default 0 check (engagement >= 0),
  status text not null default 'pending',
  last_synced timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.account_verifications (
  id bigint generated by default as identity primary key,
  account_id bigint not null unique references public.connected_accounts(id) on delete cascade,
  code text not null,
  status text not null default 'pending' check (status in ('pending', 'verified')),
  verified_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete restrict,
  type text not null,
  amount numeric(14,2) not null,
  description text not null default '',
  status text not null default 'pending' check (status in ('pending', 'processing', 'completed', 'failed', 'reversed')),
  created_at timestamptz not null default now()
);

create table if not exists public.payout_methods (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  type text not null check (type in ('stripe', 'paypal', 'crypto', 'mpesa')),
  label text not null,
  details jsonb not null default '{}'::jsonb,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  title text not null,
  message text not null default '',
  type text not null default 'system',
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  clipper_id bigint not null references public.profiles(id) on delete restrict,
  campaign_id bigint not null references public.campaigns(id) on delete restrict,
  reviewer_name text not null default 'Brand',
  rating numeric(2,1) not null check (rating between 1 and 5),
  comment text not null default '',
  created_at timestamptz not null default now(),
  unique (clipper_id, campaign_id)
);

create table if not exists public.referral_codes (
  id bigint generated by default as identity primary key,
  profile_id bigint not null unique references public.profiles(id) on delete cascade,
  code text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.referrals (
  id bigint generated by default as identity primary key,
  referrer_id bigint not null references public.profiles(id) on delete restrict,
  referred_id bigint not null unique references public.profiles(id) on delete restrict,
  referred_name text not null default '',
  referred_role text not null default '',
  code text not null,
  status text not null default 'signed_up' check (status in ('signed_up', 'rewarded')),
  reward numeric(14,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.clipper_tiers (
  id bigint generated by default as identity primary key,
  profile_id bigint not null unique references public.profiles(id) on delete cascade,
  tier text not null default 'rising' check (tier in ('rising', 'bronze', 'silver', 'gold', 'elite')),
  score integer not null default 0 check (score between 0 and 100),
  breakdown jsonb not null default '[]'::jsonb,
  computed_at timestamptz not null default now()
);

create table if not exists public.platform_admins (
  id bigint generated by default as identity primary key,
  profile_id bigint not null unique references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now()
);

create table if not exists public.user_moderation (
  id bigint generated by default as identity primary key,
  profile_id bigint not null unique references public.profiles(id) on delete restrict,
  status text not null default 'active' check (status in ('active', 'suspended')),
  updated_at timestamptz not null default now()
);

create index if not exists campaigns_status_created_idx on public.campaigns(status, created_at desc);
create index if not exists campaigns_owner_created_idx on public.campaigns(owner_id, created_at desc);
create index if not exists applications_campaign_status_idx on public.applications(campaign_id, status);
create index if not exists applications_clipper_created_idx on public.applications(clipper_id, created_at desc);
create index if not exists applications_owner_created_idx on public.applications(owner_id, created_at desc);
create index if not exists submissions_campaign_created_idx on public.submissions(campaign_id, created_at desc);
create index if not exists submissions_clipper_created_idx on public.submissions(clipper_id, created_at desc);
create index if not exists submissions_owner_created_idx on public.submissions(owner_id, created_at desc);
create index if not exists transactions_profile_created_idx on public.transactions(profile_id, created_at desc);
create index if not exists notifications_profile_created_idx on public.notifications(profile_id, created_at desc);

